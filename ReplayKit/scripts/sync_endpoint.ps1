# writes the helper address from shared/HelperEndpoint.cs, the one place it is set, out for the native plugin, the lua scripts and the controls dock; build.bat runs it before every build, and a file is only rewritten when its text changes so the plugin build can still tell it is up to date
$ErrorActionPreference = "Stop"

$repoRoot = Split-Path -Parent $PSScriptRoot
$sourcePath = Join-Path $repoRoot "shared\HelperEndpoint.cs"
if (-not (Test-Path -LiteralPath $sourcePath)) {
    throw "Missing helper endpoint source: $sourcePath"
}
$source = Get-Content -LiteralPath $sourcePath -Raw
$hostMatch = [regex]::Match($source, 'const\s+string\s+Host\s*=\s*"([^"]+)"')
$portMatch = [regex]::Match($source, 'const\s+int\s+Port\s*=\s*(\d+)\s*;')
if (-not $hostMatch.Success -or -not $portMatch.Success) {
    throw "Could not read Host and Port from $sourcePath"
}
$helperHost = $hostMatch.Groups[1].Value
$port = [int]$portMatch.Groups[1].Value
# the helper only ever listens on loopback, and every consumer pastes these into code, so anything else is refused
if ($helperHost -notmatch '^127\.\d{1,3}\.\d{1,3}\.\d{1,3}$') {
    throw "Helper host must be a loopback address, got '$helperHost'"
}
if ($port -lt 1024 -or $port -gt 65535) {
    throw "Helper port must be between 1024 and 65535, got $port"
}
$origin = "http://${helperHost}:$port"

function Write-Generated([string]$relativePath, [string]$text) {
    $path = Join-Path $repoRoot $relativePath
    New-Item -ItemType Directory -Force -Path (Split-Path -Parent $path) | Out-Null
    if ((Test-Path -LiteralPath $path) -and ([IO.File]::ReadAllText($path) -ceq $text)) { return }
    [IO.File]::WriteAllText($path, $text, [Text.UTF8Encoding]::new($false))
}

Write-Generated "plugins\replaykit\src\core\helper_endpoint.hpp" @"
// generated by scripts/sync_endpoint.ps1 from shared/HelperEndpoint.cs -- edit that file, not this one
#pragma once

namespace rk {

inline constexpr char kHelperHost[] = "$helperHost";
inline constexpr int kHelperPort = $port;

} // namespace rk

"@

Write-Generated "lua\helper\helper_endpoint.lua" @"
-- generated by scripts/sync_endpoint.ps1 from shared/HelperEndpoint.cs -- edit that file, not this one
return { host = "$helperHost", port = $port, origin = "$origin" }

"@

Write-Generated "ui\helper-endpoint.js" @"
// generated by scripts/sync_endpoint.ps1 from shared/HelperEndpoint.cs -- edit that file, not this one
window.RK_HELPER_ORIGIN = "$origin";

"@

Write-Host "    ReplayKit helper $origin"
